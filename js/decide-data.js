  (function validate() {
    const problems = [];
    const ids = new Set();
    SCENARIOS.forEach((s) => {
      if (ids.has(s.id)) problems.push("სცენარის id მეორდება: " + s.id);
      ids.add(s.id);
      const cardIds = new Set();
      s.cards.forEach((c) => {
        const where = s.id + " / " + c.id;
        if (cardIds.has(c.id)) problems.push(where + ": ბარათის id მეორდება");
        cardIds.add(c.id);
        if (s.lessons.indexOf(c.lesson) === -1) problems.push(where + ": lesson სცენარის lessons სიაში არ არის");
        ["left", "right"].forEach((side) => {
          const opt = c[side];
          if (!opt || !opt.label || !opt.outcome) problems.push(where + ": " + side + " — label/outcome აკლია");
          SCALES.forEach((k) => {
            if (!opt || !Number.isInteger(opt.effects && opt.effects[k])) problems.push(where + ": " + side + ".effects." + k + " უნდა იყოს რიცხვი");
          });
        });
        if (c.historical !== null && c.historical !== "left" && c.historical !== "right") problems.push(where + ": historical — left, right ან null");
        if (!c.history) problems.push(where + ": history აკლია");
      });
      ["economy", "army", "legitimacy", "survived", "triumph"].forEach((k) => {
        if (!s.endings || !s.endings[k]) problems.push(s.id + ": endings." + k + " აკლია");
      });
    });
    if (problems.length) console.warn("IMS_DECIDE — შეცდომები:\n• " + problems.join("\n• "));
  })();

