        ids.add(c.id);
        const parts = parse(c.text);
        const fakes = parts.filter((p) => p.kind === "fake");
        const truths = parts.filter((p) => p.kind === "true");
        if (fakes.length < 2 || fakes.length > 3) warn("[detective] " + c.id + ": ყალბი დეტალი უნდა იყოს 2–3, არის " + fakes.length);
