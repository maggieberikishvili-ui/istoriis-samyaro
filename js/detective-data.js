  const TOKEN = /\[([^\]]+)\]|\{([^}]+)\}/g;

  /**
   * ტექსტი → ნაწილები: { kind: "plain" | "true" | "fake", text, fix, why, anachronism }
   */
  function parse(text) {
    const parts = [];
    let last = 0;
    let m;
    TOKEN.lastIndex = 0;
    while ((m = TOKEN.exec(text))) {
      if (m.index > last) parts.push({ kind: "plain", text: text.slice(last, m.index) });
      if (m[1] !== undefined) {
        parts.push({ kind: "true", text: m[1] });
      } else {
        const anachronism = m[2].charAt(0) === "!";
        const f = (anachronism ? m[2].slice(1) : m[2]).split("|");
        parts.push(anachronism
          ? { kind: "fake", anachronism: true, text: f[0], fix: "", why: f[1] || "" }
          : { kind: "fake", anachronism: false, text: f[0], fix: f[1] || "", why: f[2] || "" });
      }
      last = TOKEN.lastIndex;
    }
    if (last < text.length) parts.push({ kind: "plain", text: text.slice(last) });
    return parts;
  }

